SKIP_NOTES = [
    '元结《贼退示官吏》《石鱼湖上醉歌》：长篇古诗，暂不硬补',
    '李颀《听董大弹胡笳兼寄语弄房给事》、杜甫《观公孙大娘弟子舞剑器行》：长篇歌行，暂不硬补',
    '岑参《与高适薛据登慈恩寺浮图》：长篇，暂不硬补',
    '杜审言《和晋陵陆丞早春游望》、张乔书边事已补；唐玄宗以李隆基名补入',
]


def main():
    con = sqlite3.connect(DB)
    c = con.cursor()
    maxid = c.execute('SELECT MAX(CAST(id AS INTEGER)) FROM poems').fetchone()[0] or 0
    inserted, skipped = [], []
    nid = maxid + 1
    for title, author, dynasty, genre, content in ENTRIES:
        probe_raw = content.replace('\n', '')[:14]
        exist = c.execute('SELECT id FROM poems WHERE author=? AND title=? AND instr(content,?)>0 LIMIT 1', (author, title, probe_raw)).fetchone()
        if exist:
            skipped.append((title, author, '已存在'))
            continue
        c.execute('INSERT INTO poems (id,title,author,dynasty,genre,content) VALUES (?,?,?,?,?,?)',
                  (str(nid), title, author, dynasty, genre, content))
        inserted.append((title, author, nid))
        nid += 1
    con.commit()
    print(f'插入 {len(inserted)} 条（id {maxid + 1}~{nid - 1}）')
    for t, a, i in inserted:
        print(f'  + [{a}]《{t}》 id={i}')
    for t, a, why in skipped:
        print(f'  = [{a}]《{t}》 {why}')
    print('--- 未补说明 ---')
    for s in SKIP_NOTES:
        print('  -', s)
    con.close()


if __name__ == '__main__':
    main()